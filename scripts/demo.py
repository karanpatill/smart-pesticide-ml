"""Repeatable demonstration of the end-to-end software pipeline.

    python scripts/demo.py

Runs fixed cases and writes reports/demo/demo_results.json and docs/DEMO_REPORT.md.
Every case is labelled by evidence type:
  PUBLIC-DATASET IMAGE  - real held-out TEST image from a public dataset; outputs are ACTUAL model predictions
  SYNTHETIC FIXTURE     - row of the synthetic Model 2 dataset (synthetic data, synthetic label)
  CONSTRUCTED INPUT     - hand-made invalid input to exercise validation (not a measurement)
  ILLUSTRATIVE RECORD   - device-format record with made-up numbers (NOT a measurement)
No hardware is involved; nothing here is a sensor measurement.
"""

from __future__ import annotations

import io
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from analyze import summary  # noqa: E402
from fruitvision.system import SmartPesticideSystem  # noqa: E402


def pick_images():
    p = pd.read_csv(ROOT / "reports/model3/postprocess/fruit_confidence_test.csv")
    out = []
    for fruit, cond in (("banana", "correct_high"), ("tomato", "correct_high"), ("guava", "low")):
        g = p[p.fruit == fruit]
        g = g[g.correct & (g.conf >= 0.976)] if cond == "correct_high" else g[g.conf < 0.976]
        out.append((f"{fruit} ({'confident' if cond == 'correct_high' else 'low fruit confidence'})",
                    ROOT / "data/raw" / g.sort_values("path").iloc[0].path))
    return out


def main() -> None:
    sysm = SmartPesticideSystem(ROOT)
    fx = json.loads((ROOT / "data/fixtures/sensor_records.json").read_text())["records"]
    grey = io.BytesIO()
    Image.fromarray(np.full((240, 240, 3), 128, np.uint8)).save(grey, format="PNG")
    imgs = pick_images()
    cases = [
        (f"A. {imgs[0][0]} + synthetic MEDIUM fixture", "PUBLIC-DATASET IMAGE + SYNTHETIC FIXTURE", imgs[0][1], "synthetic_medium"),
        (f"B. {imgs[1][0]} + synthetic HIGH fixture", "PUBLIC-DATASET IMAGE + SYNTHETIC FIXTURE", imgs[1][1], "synthetic_high"),
        (f"C. {imgs[2][0]} + synthetic LOW fixture", "PUBLIC-DATASET IMAGE + SYNTHETIC FIXTURE", imgs[2][1], "synthetic_low"),
        ("D. uniform grey frame (camera fault) + DHT22 NaN", "CONSTRUCTED INPUT", grey.getvalue(), "invalid_dht22_nan"),
        (f"E. {imgs[0][0]} + disconnected TCS34725", "PUBLIC-DATASET IMAGE + CONSTRUCTED INPUT", imgs[0][1], "invalid_tcs_disconnected"),
        ("F. sensors only: device-format record, uncalibrated", "ILLUSTRATIVE RECORD", None, "device_like_uncalibrated"),
        ("G. sensors only: MQ135 outside synthetic training range", "CONSTRUCTED INPUT", None, "out_of_range_mq135"),
    ]
    results, md = [], []
    md += ["# Demo report (generated by `python scripts/demo.py`)", "",
           f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')} on the development PC. "
           "**No hardware was used; no value below is a sensor measurement.**", "",
           "Evidence labels: **PUBLIC-DATASET IMAGE** = actual model prediction on a held-out public test image; "
           "**SYNTHETIC FIXTURE** = row of the synthetic Model 2 dataset; **CONSTRUCTED INPUT** = hand-made invalid "
           "input; **ILLUSTRATIVE RECORD** = made-up device-format numbers.", "",
           "The pesticide-risk category always comes from a SYNTHETIC-DATA PROTOTYPE: it is not a measurement, "
           "LOW is not evidence of absence, HIGH is not proof of presence.", ""]
    for title, evidence, image, fxname in cases:
        r = sysm.analyze(image=image, sensors=fx[fxname]["record"])
        img_label = (str(Path(image).relative_to(ROOT)) if isinstance(image, Path) else
                     ("constructed in memory" if image is not None else "none"))
        results.append({"case": title, "evidence": evidence, "image": img_label, "sensor_fixture": fxname,
                        "sensor_fixture_note": fx[fxname].get("constructed") or
                        f"synthetic row {fx[fxname].get('source_row')} (synthetic label {fx[fxname].get('synthetic_target_label')})",
                        "result": r})
        md += [f"## {title}", f"*Evidence:* **{evidence}**  ", f"*Image:* `{img_label}`  ",
               f"*Sensor record:* `{fxname}` — {results[-1]['sensor_fixture_note']}", "", "```", summary(r), "```", ""]
    out = ROOT / "reports/demo"
    out.mkdir(parents=True, exist_ok=True)
    (out / "demo_results.json").write_text(json.dumps(results, indent=2, default=str))
    (ROOT / "docs/DEMO_REPORT.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()

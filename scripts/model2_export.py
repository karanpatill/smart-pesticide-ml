"""Deterministic export of the selected Model 2 prototype (S__logreg) for embedded use.

Reads models/model2_prototype/S__logreg.joblib (READ-ONLY; never rewritten) and writes
models/model2_export/:
  model2_logreg.json   feature order, derived-feature formulas, scaler mean/scale,
                       coefficients, intercepts, class order, synthetic training ranges,
                       provenance (source sha256, sklearn version)
  model2_logreg_params.h   C header with the same numbers (float32 literals)
The C inference code lives in firmware/model2/model2_infer.{h,c}.

SYNTHETIC PROTOTYPE: these parameters were fitted on synthetic data only.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "models/model2_prototype/S__logreg.joblib"
OUT = ROOT / "models/model2_export"
CLASSES = ["LOW", "MEDIUM", "HIGH"]          # model2_train.py: label index order
RAW = ["sensor_tcs_r", "sensor_tcs_g", "sensor_tcs_b", "sensor_tcs_c",
       "sensor_mq135", "sensor_ph", "sensor_temp_c", "sensor_humidity_pct"]
DERIVED = {"drv_tcs_r_over_c": "sensor_tcs_r / sensor_tcs_c", "drv_tcs_g_over_c": "sensor_tcs_g / sensor_tcs_c",
           "drv_tcs_b_over_c": "sensor_tcs_b / sensor_tcs_c", "drv_log_mq135": "ln(sensor_mq135)"}


def main() -> None:
    pipe = joblib.load(SRC)
    pre, clf = pipe.named_steps["pre"], pipe.named_steps["clf"]
    names = list(pre.feature_names_in_)
    assert names == RAW + list(DERIVED), names
    assert len(pre.transformers_) == 1 or all(t[0] in ("num", "remainder") for t in pre.transformers_)
    sc = pre.named_transformers_["num"]
    assert list(clf.classes_) == [0, 1, 2]
    # synthetic training ranges (TRAIN split rows only), used for out-of-range checks
    syn = pd.read_csv(ROOT / "data/synthetic/model2/model2_synthetic_v1.csv")
    sp = pd.read_csv(ROOT / "data/synthetic/model2/splits_v1.csv")
    tr = syn.merge(sp[["meta_sample_id", "split"]], on="meta_sample_id").query("split != 'test'")
    ranges = {c: {"min": float(tr[c].min()), "max": float(tr[c].max()),
                  "p0_5": float(tr[c].quantile(0.005)), "p99_5": float(tr[c].quantile(0.995))} for c in RAW}

    spec = {
        "model": "Model 2 prototype: multinomial logistic regression (sensor features only, S__logreg)",
        "evidence_level": "SYNTHETIC PROTOTYPE - fitted on synthetic data; not validated on real sensors or pesticides",
        "classes": CLASSES,
        "raw_inputs": RAW,
        "derived_features": DERIVED,
        "feature_order": names,
        "scaler_mean": sc.mean_.tolist(),
        "scaler_scale": sc.scale_.tolist(),
        "coef": clf.coef_.tolist(),
        "intercept": clf.intercept_.tolist(),
        "inference": "z = (x - mean) / scale; logits = coef @ z + intercept; p = softmax(logits); class = argmax",
        "synthetic_training_ranges_trainval": ranges,
        "units_note": ("Inputs must be on the SAME scales as the synthetic generator "
                       "(configs/model2_synthetic.yaml): TCS counts at counts_full_scale=1000, MQ135 raw-ADC-like "
                       "scale of Zenodo 17285312, pH units, deg C, %RH. Real device readings need a measured "
                       "calibration mapping before this model can be applied."),
        "provenance": {"source": str(SRC.relative_to(ROOT)).replace("\\", "/"),
                       "source_sha256": hashlib.sha256(SRC.read_bytes()).hexdigest(),
                       "sklearn": sklearn.__version__, "python": sys.version.split()[0]},
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "model2_logreg.json").write_text(json.dumps(spec, indent=2))

    def arr(a):
        return ", ".join(f"{float(v):.9g}f" for v in np.ravel(a))
    h = f"""/* AUTO-GENERATED by scripts/model2_export.py - DO NOT EDIT.
 * Model 2 prototype (multinomial logistic regression). SYNTHETIC PROTOTYPE:
 * fitted on synthetic data only; not a validated pesticide detector.
 * Source: {spec['provenance']['source']} sha256={spec['provenance']['source_sha256']}
 * Feature order: {', '.join(names)}
 * Class order: {', '.join(CLASSES)}
 */
#ifndef MODEL2_LOGREG_PARAMS_H
#define MODEL2_LOGREG_PARAMS_H

#define M2_N_FEATURES {len(names)}
#define M2_N_CLASSES {len(CLASSES)}

static const float M2_MEAN[M2_N_FEATURES] = {{{arr(sc.mean_)}}};
static const float M2_SCALE[M2_N_FEATURES] = {{{arr(sc.scale_)}}};
static const float M2_COEF[M2_N_CLASSES][M2_N_FEATURES] = {{
{chr(10).join('    {' + arr(row) + '},' for row in clf.coef_)}
}};
static const float M2_INTERCEPT[M2_N_CLASSES] = {{{arr(clf.intercept_)}}};

#endif /* MODEL2_LOGREG_PARAMS_H */
"""
    (OUT / "model2_logreg_params.h").write_text(h, newline="\n")
    print(json.dumps({k: spec[k] for k in ("classes", "feature_order", "provenance")}, indent=1))


if __name__ == "__main__":
    main()

"""Extract the OV2640 configuration that the ENTC firmware writes (and that produced the verified live frames) from
the hash-checked backup of the original firmware into a generated C header. Nothing is typed by hand.

Evidence (disassembly of the backup, see docs/BOARD_PIN_MAP_EVIDENCE.md):
  camera init @0x08001F96: SCCB write (0xFF <- 0x01), table A @0x0800711C len 314 B (157 reg/val pairs),
  delay 10 ms, table B @0x08007258 len 44 B (22 pairs); retried up to 3 times.
  PCLK search @0x08002006: for v in table C @0x08007284 (3 B): SCCB 0xFF <- 0x00, 0xD3 <- (v | 0x80).
Usage: python tools/firmware/extract_entc_config.py [out.h]
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKUP = ROOT / "backups/board_original_firmware/board_flash_0x08000000_512K.bin"
BACKUP_SHA256 = "1590cd4e57f3b6b60d48eeefa28b4f502e057591890221fa4ca3d2b1b417601c"
OUT = ROOT / "firmware/stm32f407/generated/fv_entc_ov2640_tables.h"
TABLE_A, LEN_A = 0x0800711C, 314
TABLE_B, LEN_B = 0x08007258, 44
TABLE_C, LEN_C = 0x08007284, 3


def extract(data: bytes) -> dict:
    off = lambda a: a - 0x08000000
    a = data[off(TABLE_A):off(TABLE_A) + LEN_A]
    b = data[off(TABLE_B):off(TABLE_B) + LEN_B]
    c = data[off(TABLE_C):off(TABLE_C) + LEN_C]
    return {"A": [(a[i], a[i + 1]) for i in range(0, LEN_A, 2)], "B": [(b[i], b[i + 1]) for i in range(0, LEN_B, 2)],
            "C": list(c)}


def render(t: dict) -> str:
    pairs = lambda p: ",\n".join("    " + ", ".join(f"{{0x{r:02X}, 0x{v:02X}}}" for r, v in p[i:i + 8]) for i in range(0, len(p), 8))
    return f"""/* GENERATED by tools/firmware/extract_entc_config.py - do not edit.
 * Source: original ENTC firmware backup, sha256 {BACKUP_SHA256}
 * (backups/board_original_firmware/board_flash_0x08000000_512K.bin). These are the OV2640 register writes of the
 * ENTC firmware that produced the live frames verified over SWD (160x120 RGB565 big-endian, VSPOL=0, HSPOL=0).
 * Sequence (ENTC @0x08001F96): SCCB 0xFF<-0x01, table A, wait 10 ms, table B. PCLK: 0xFF<-0x00, 0xD3<-(C[i]|0x80). */
#ifndef FV_ENTC_OV2640_TABLES_H
#define FV_ENTC_OV2640_TABLES_H
#include <stdint.h>

typedef struct {{ uint8_t reg, val; }} fv_sccb_reg_t;

#define FV_ENTC_OV2640_TABLE_A_ADDR 0x{TABLE_A:08X}u
#define FV_ENTC_OV2640_TABLE_A_LEN {len(t["A"])}
static const fv_sccb_reg_t FV_ENTC_OV2640_TABLE_A[{len(t["A"])}] = {{
{pairs(t["A"])}
}};

#define FV_ENTC_OV2640_TABLE_B_ADDR 0x{TABLE_B:08X}u
#define FV_ENTC_OV2640_TABLE_B_LEN {len(t["B"])}
static const fv_sccb_reg_t FV_ENTC_OV2640_TABLE_B[{len(t["B"])}] = {{
{pairs(t["B"])}
}};

/* R_DVP_SP (DSP bank 0x00, reg 0xD3) divider candidates tried in order; written as value | 0x80. */
#define FV_ENTC_OV2640_PCLK_N {len(t["C"])}
static const uint8_t FV_ENTC_OV2640_PCLK_DIV[{len(t["C"])}] = {{{", ".join(f"0x{v:02X}" for v in t["C"])}}};

#endif
"""


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    data = BACKUP.read_bytes()
    h = hashlib.sha256(data).hexdigest()
    if h != BACKUP_SHA256:
        print(f"backup hash mismatch {h}", file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(extract(data)), encoding="ascii", newline="\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())

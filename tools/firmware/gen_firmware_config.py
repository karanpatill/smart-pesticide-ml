"""Generate firmware/stm32f407/generated/fv_generated_config.h from the frozen artifacts.

Sources (read-only): models/experimental/tflite/combined_int8.tflite, models/model3/labels.json,
models/model3/postprocess_config.json, models/model3/shelf_life_ranges.json,
configs/image_checks.json, models/model2_export/model2_logreg.json.
The TFLM output index of every head is taken from the model's SIGNATURE output names (not guessed).

Usage: python tools/firmware/gen_firmware_config.py [OUT_PATH]   (default: committed location)
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "models/experimental/tflite/combined_int8.tflite"
OUT = ROOT / "firmware/stm32f407/generated/fv_generated_config.h"
HEADS = ["fruit", "condition", "quality_banana", "quality_guava", "quality_apple",
         "stage_tomato", "stage_brinjal", "stage_banana"]
FRUITS = ["apple", "banana", "guava", "tomato", "brinjal"]
CONDITIONS = ["fresh", "spoiled"]
STAGES = ["Fresh", "Semi-fresh", "Rotten"]
M2_RAW = ["sensor_tcs_r", "sensor_tcs_g", "sensor_tcs_b", "sensor_tcs_c",
          "sensor_mq135", "sensor_ph", "sensor_temp_c", "sensor_humidity_pct"]
# Arena sizes: host 32-bit TFLM measurement (CMSIS-NN int8-only) rounded up; PENDING on-target confirmation.
ARENA_PERSISTENT = 53248      # measured minimum 53,120 B
ARENA_NONPERSISTENT = 97280   # measured 96,000 B + estimated CMSIS-NN DSP scratch 864 B, rounded up


def cf(x: float) -> str:
    """C float literal that is always valid (e.g. 1 -> '1.0f', 0.00390625 -> '0.00390625f')."""
    t = f"{float(x):.9g}"
    if not any(c in t for c in ".eEn"):
        t += ".0"
    return t + "f"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


import argparse

def model_meta(model_path: Path = MODEL) -> dict:
    import tensorflow as tf
    it = tf.lite.Interpreter(model_path=str(model_path),
                             experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
    it.allocate_tensors()
    order = [d["index"] for d in it.get_output_details()]          # TFLM output j == subgraph output order
    sig = it.get_signature_runner().get_output_details()           # name -> details (with tensor index)
    tensor_of = {name: d["index"] for name, d in sig.items()}
    inp = it.get_input_details()[0]
    outs = {d["index"]: d for d in it.get_output_details()}
    head_j, head_n, oq = {}, {}, set()
    for h in HEADS:
        t = tensor_of[h]
        head_j[h] = order.index(t)
        head_n[h] = int(np.prod(outs[t]["shape"]))
        oq.add(tuple(float(x) for x in outs[t]["quantization"]))
    assert len(oq) == 1, f"outputs have different quantisation: {oq}"
    res = {"in_shape": [int(x) for x in inp["shape"]], "in_q": inp["quantization"], "in_dtype": inp["dtype"].__name__,
           "out_q": oq.pop(), "head_j": head_j, "head_n": head_n, "n_outputs": len(order)}
    if "presence" in tensor_of:
        res["presence_j"] = order.index(tensor_of["presence"])
    return res


def cstr_array(name: str, items: list[str]) -> str:
    return f"static const char *const {name}[{len(items)}] = {{{', '.join(json.dumps(s) for s in items)}}};"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out", nargs="?", default=str(OUT), type=Path)
    ap.add_argument("--model", type=Path, default=MODEL)
    a = ap.parse_args()
    model_path = a.model
    out = a.out
    mm = model_meta(model_path)
    labels = json.loads((ROOT / "models/model3/labels.json").read_text())
    pp = json.loads((ROOT / "models/model3/postprocess_config.json").read_text())
    shelf = json.loads((ROOT / "models/model3/shelf_life_ranges.json").read_text())
    img = json.loads((ROOT / "configs/image_checks.json").read_text())
    m2 = json.loads((ROOT / "models/model2_export/model2_logreg.json").read_text())
    for h in HEADS[2:]:
        assert len(labels[h]) == mm["head_n"][h], h
    assert mm["head_n"]["fruit"] == 5 and mm["head_n"]["condition"] == 2
    srcs = {"model": model_path, "labels": ROOT / "models/model3/labels.json",
            "postprocess": ROOT / "models/model3/postprocess_config.json",
            "shelf": ROOT / "models/model3/shelf_life_ranges.json", "image_checks": ROOT / "configs/image_checks.json",
            "model2_export": ROOT / "models/model2_export/model2_logreg.json"}
    L = ["/* AUTO-GENERATED by tools/firmware/gen_firmware_config.py - DO NOT EDIT.",
         " * Constants derived from frozen artifacts (sha256 below). Regenerate if any source changes;",
         " * tests/test_fw_generated_config.py fails on drift. */",
         "#ifndef FV_GENERATED_CONFIG_H", "#define FV_GENERATED_CONFIG_H", "", "#include <stdint.h>", ""]
    for k, p in srcs.items():
        L.append(f'#define FV_SRC_SHA256_{k.upper()} "{sha(p)}"')
    L += ["", f"#define FV_MODEL_BYTES {model_path.stat().st_size}u",
          f"#define FV_MODEL_IN_H {mm['in_shape'][1]}", f"#define FV_MODEL_IN_W {mm['in_shape'][2]}",
          f"#define FV_MODEL_IN_C {mm['in_shape'][3]}",
          f"#define FV_MODEL_IN_SCALE {cf(mm['in_q'][0])}", f"#define FV_MODEL_IN_ZERO_POINT ({mm['in_q'][1]})",
          f"#define FV_MODEL_OUT_SCALE {cf(mm['out_q'][0])}", f"#define FV_MODEL_OUT_ZERO_POINT ({int(mm['out_q'][1])})",
          f"#define FV_MODEL_N_OUTPUTS {mm['n_outputs']}"]
    if "presence_j" in mm:
        L += [f"#define FV_PRESENCE_OUTPUT_INDEX {mm['presence_j']}"]
    arena_pers = 54272 if "presence_j" in mm else ARENA_PERSISTENT
    L += ["",
          "/* Tensor arenas (TFLM split allocator). Host 32-bit measurement, rounded up; PENDING on-target check. */",
          f"#define FV_ARENA_PERSISTENT_BYTES {arena_pers}u     /* -> CCM  (CPU-only TFLM data) */",
          f"#define FV_ARENA_NONPERSISTENT_BYTES {ARENA_NONPERSISTENT}u  /* -> SRAM1 (activations, I/O, scratch; camera reuse) */",
          "", "typedef enum {"]
    L += [f"    FV_HEAD_{h.upper()} = {i}," for i, h in enumerate(HEADS)] + ["    FV_N_HEADS = 8", "} fv_head_t;", ""]
    L.append("/* TFLM output tensor index of each head (from signature names). */")
    L.append(f"static const uint8_t FV_HEAD_OUTPUT_INDEX[FV_N_HEADS] = {{{', '.join(str(mm['head_j'][h]) for h in HEADS)}}};")
    L.append(f"static const uint8_t FV_HEAD_N_CLASSES[FV_N_HEADS] = {{{', '.join(str(mm['head_n'][h]) for h in HEADS)}}};")
    L += ["", "typedef enum { FV_FRUIT_APPLE = 0, FV_FRUIT_BANANA, FV_FRUIT_GUAVA, FV_FRUIT_TOMATO, FV_FRUIT_BRINJAL, "
          "FV_N_FRUITS } fv_fruit_t;", cstr_array("FV_FRUIT_LABELS", FRUITS), cstr_array("FV_CONDITION_LABELS", CONDITIONS)]
    for h in HEADS[2:]:
        L.append(cstr_array(f"FV_LABELS_{h.upper()}", [labels[h][str(i)] for i in range(len(labels[h]))]))
    L += ["", "/* Post-processing (configs/model3_postprocess.json). Threshold was derived on FLOAT outputs;",
          " * re-derive on INT8/TFLM outputs before relying on it (PENDING). */",
          f"#define FV_FRUIT_CONF_THRESHOLD {cf(pp['fruit_confidence_threshold'])}", "",
          "/* Shelf-life lookup [fruit][stage] in days; -1 = not available (AgriFreshNET storage conditions only). */",
          "static const int8_t FV_SHELF_RANGE_DAYS[FV_N_FRUITS][3][2] = {"]
    for f in FRUITS:
        r = shelf["ranges"].get(f)
        cells = [f"{{{r[s][0]}, {r[s][1]}}}" if r else "{-1, -1}" for s in STAGES]
        L.append(f"    /* {f:8s} */ {{{', '.join(cells)}}},")
    L += ["};", "", "/* Image sanity checks on the 80x80 model input (configs/image_checks.json). */",
          f"#define FV_IMG_REJECT_LUM_STD_BELOW {cf(img['reject']['lum_std_below'])}",
          f"#define FV_IMG_REJECT_LAG1_AUTOCORR_BELOW {cf(img['reject']['lag1_autocorr_below'])}",
          f"#define FV_IMG_REJECT_CHROMA_BELOW {cf(img['reject']['chroma_below'])}",
          f"#define FV_IMG_WARN_LUM_MEAN_BELOW {cf(img['warn']['lum_mean_below'])}",
          f"#define FV_IMG_WARN_LUM_MEAN_ABOVE {cf(img['warn']['lum_mean_above'])}",
          f"#define FV_IMG_WARN_CLIPPED_FRACTION_ABOVE {cf(img['warn']['clipped_fraction_above'])}",
          f"#define FV_IMG_REJECT_MIN_SIDE {int(img['dimensions']['reject_min_side'])}",
          f"#define FV_IMG_WARN_MIN_SIDE {int(img['dimensions']['warn_min_side'])}",
          f"#define FV_IMG_WARN_ASPECT_RATIO {cf(img['dimensions']['warn_aspect_ratio'])}", "",
          "/* Model 2 synthetic training ranges (train+val), order: TCS R,G,B,C, MQ135, pH, temp, RH. */",
          "#define FV_M2_OOD_MARGIN 0.10f",
          "static const float FV_M2_RANGE_MIN[8] = {" + ", ".join(cf(m2['synthetic_training_ranges_trainval'][c]['min']) for c in M2_RAW) + "};",
          "static const float FV_M2_RANGE_MAX[8] = {" + ", ".join(cf(m2['synthetic_training_ranges_trainval'][c]['max']) for c in M2_RAW) + "};",
          "", "#endif /* FV_GENERATED_CONFIG_H */", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), newline="\n")
    print(f"wrote {out}  head->output index: {mm['head_j']}")


if __name__ == "__main__":
    main()

"""Emit g_fv_model_data (16-byte aligned, const -> .rodata/flash) from the frozen INT8 model.
Output goes to a build directory; the frozen .tflite is only read (hash checked)."""
import argparse, hashlib, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MODEL = ROOT / "models/experimental/tflite/combined_int8.tflite"
EXPECTED_PREFIX = "1af166f0b07c"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=pathlib.Path)
    ap.add_argument("--model", type=pathlib.Path, default=MODEL)
    a = ap.parse_args()
    b = a.model.read_bytes()
    h = hashlib.sha256(b).hexdigest()
    if a.model == MODEL and not h.startswith(EXPECTED_PREFIX):
        print(f"model hash mismatch: {h}", file=sys.stderr)
        return 1
    a.out.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"/* GENERATED by tools/firmware/gen_model_data.py from {a.model.name} sha256={h} */",
             "#include <stdint.h>",
             "__attribute__((aligned(16))) const unsigned char g_fv_model_data[] = {"]
    for i in range(0, len(b), 24):
        lines.append("  " + ",".join(str(x) for x in b[i:i + 24]) + ",")
    lines += ["};", f"const unsigned int g_fv_model_len = {len(b)}u;", ""]
    a.out.write_text("\n".join(lines), encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#include "fv_ssd1306.h"

#include <string.h>

/* ENTC order: off, horizontal addressing, page 0, COM scan remap, column 0, start line 0, contrast 0xFF, segment
 * remap, normal, mux 64, resume RAM, offset 0, clock 0xF0, precharge 0x22, COM pins 0x12, VCOMH 0x20,
 * charge pump on, display on. */
static const uint8_t INIT_CMDS[] = {0xAE, 0x20, 0x00, 0xB0, 0xC8, 0x00, 0x10, 0x40, 0x81, 0xFF, 0xA1, 0xA6,
                                    0xA8, 0x3F, 0xA4, 0xD3, 0x00, 0xD5, 0xF0, 0xD9, 0x22, 0xDA, 0x12, 0xDB,
                                    0x20, 0x8D, 0x14, 0xAF};

static int cmds(fv_ssd1306_t *d, const uint8_t *c, size_t n) {
    const uint8_t ctl = 0x00;
    return fv_i2c_write(d->bus, d->addr8, &ctl, 1, c, n) == FV_BB_OK ? FV_SSD1306_OK : FV_SSD1306_ERR_BUS;
}

int fv_ssd1306_init(fv_ssd1306_t *d) {
    if (!d || !d->bus) return FV_SSD1306_ERR_ARG;
    fv_ssd1306_clear(d);
    if (cmds(d, INIT_CMDS, sizeof INIT_CMDS)) return FV_SSD1306_ERR_BUS;
    return fv_ssd1306_flush(d);
}

void fv_ssd1306_clear(fv_ssd1306_t *d) {
    if (d) memset(d->fb, 0, sizeof d->fb);
}

void fv_ssd1306_draw_char(fv_ssd1306_t *d, int col, int row, char ch) {
    if (!d || col < 0 || col > 20 || row < 0 || row > 7) return;
    const unsigned char u = (unsigned char)ch;
    const uint8_t *g = FV_FONT5X7[(u < 0x20 || u > 0x7E) ? ('?' - 0x20) : (u - 0x20)];
    uint8_t *p = &d->fb[row * 128 + col * 6];
    for (int i = 0; i < 5; ++i) p[i] = g[i];
    p[5] = 0;
}

void fv_ssd1306_draw_text(fv_ssd1306_t *d, int col, int row, const char *s) {
    for (; s && *s && col <= 20; ++s, ++col) fv_ssd1306_draw_char(d, col, row, *s);
}

int fv_ssd1306_get_pixel(const fv_ssd1306_t *d, int x, int y) {
    if (!d || x < 0 || x > 127 || y < 0 || y > 63) return 0;
    return (d->fb[(y >> 3) * 128 + x] >> (y & 7)) & 1;
}

/* Per-page update exactly like the original ENTC firmware (@0x080031A0): for each page send 0xB0+page, 0x00, 0x10
 * (page address, column 0), then the page's 128 bytes in ONE data transfer. Does not rely on automatic page
 * advance, so all 8 pages are written on SSD1306 and compatible controllers. */
int fv_ssd1306_flush(fv_ssd1306_t *d) {
    if (!d || !d->bus) return FV_SSD1306_ERR_ARG;
    const uint8_t ctl = 0x40;
    int r = FV_SSD1306_OK;
    for (int page = 0; page < 8; ++page) {          /* keep going: one failed page must not blank the rest */
        const uint8_t addr[3] = {(uint8_t)(0xB0 + page), 0x00, 0x10};
        if (cmds(d, addr, sizeof addr) ||
            fv_i2c_write(d->bus, d->addr8, &ctl, 1, &d->fb[page * 128], 128) != FV_BB_OK)
            r = FV_SSD1306_ERR_BUS;
    }
    return r;
}

